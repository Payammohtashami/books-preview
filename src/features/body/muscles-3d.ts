import * as THREE from 'three';
import { loft, TORSO, type Sec } from './body-skin';
import { prof, pv, taper, type MatFactory, type MatKind, type P3 } from './skeleton-3d';

const PI = Math.PI;
const V = (x: number, y: number, z: number) => new THREE.Vector3(x, y, z);
const lerp = (a: number, b: number, t: number) => a + (b - a) * t;
const sgnPow = (v: number, p: number) => Math.sign(v) * Math.abs(v) ** p;
const PX = V(1, 0, 0);
const PZ = V(0, 0, 1);

/** مقطع تنه (نیم‌پهنا و عمق) در ارتفاع y از جدول پوست */
function torsoRow(y: number): { X: number; zf: number; zb: number } {
  const rows = TORSO;
  if (y >= rows[0][0]) return { X: rows[0][1], zf: rows[0][2], zb: rows[0][3] };
  for (let i = 0; i + 1 < rows.length; i += 1) {
    const a = rows[i]; const b = rows[i + 1];
    if (y <= a[0] && y >= b[0]) { const t = (a[0] - y) / (a[0] - b[0]); return { X: lerp(a[1], b[1], t), zf: lerp(a[2], b[2], t), zb: lerp(a[3], b[3], t) }; }
  }
  const l = rows[rows.length - 1];
  return { X: l[1], zf: l[2], zb: l[3] };
}
/** نقطه روی سطح تنه: phi از صفر (وسط پشت) تا π (وسط جلو) برای نیمهٔ راست؛ inset به داخل */
function torsoSurf(y: number, phi: number, inset: number): THREE.Vector3 {
  const r = torsoRow(y);
  const hd = (r.zf - r.zb) / 2; const zc = (r.zf + r.zb) / 2; const p = 2 / 2.6;
  return V((r.X - inset) * sgnPow(Math.sin(phi), p), y, zc + (hd - inset) * sgnPow(-Math.cos(phi), p));
}

type Stops = Array<[number, number, number]>;
export const spindle = (a: number, b: number): Stops => [[0, 0.0045, 0.004], [0.14, a * 0.45, b * 0.45], [0.45, a, b], [0.78, a * 0.55, b * 0.55], [1, 0.0045, 0.004]];
export const strap = (a: number, b: number): Stops => [[0, a * 0.6, b * 0.7], [0.5, a, b], [1, a * 0.6, b * 0.7]];

function profAt(stops: Stops, t: number): [number, number] {
  for (let i = 0; i + 1 < stops.length; i += 1) {
    if (t >= stops[i][0] && t <= stops[i + 1][0]) {
      const u = (t - stops[i][0]) / (stops[i + 1][0] - stops[i][0] || 1);
      const w = (1 - Math.cos(PI * u)) / 2;
      return [lerp(stops[i][1], stops[i + 1][1], w), lerp(stops[i][2], stops[i + 1][2], w)];
    }
  }
  const l = stops[stops.length - 1];
  return [l[1], l[2]];
}

